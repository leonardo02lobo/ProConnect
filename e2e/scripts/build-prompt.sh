#!/usr/bin/env bash
# Builds the full prompt for an AI task from e2e/prompts/<task>.md + run context.
# Used by BOTH the local scripts (ai-triage.sh / ai-heal.sh) and the GitHub workflows,
# so local and CI runs see exactly the same instructions.
#   build-prompt.sh <triage|heal> <test-results dir> [artifacts dir] [output file]
set -euo pipefail
TASK="${1:?task: triage|heal}"
RESULTS_DIR="${2:-e2e/test-results}"
ARTIFACTS_DIR="${3:-e2e/artifacts}"
OUTPUT_FILE="${4:-e2e/ai-${TASK}.md}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PROMPT="$ROOT/e2e/prompts/${TASK}.md"
[[ -f "$PROMPT" ]] || { echo "missing prompt $PROMPT" >&2; exit 1; }

cat "$PROMPT"
cat <<CTX

---
# Run context (generated by e2e/scripts/build-prompt.sh)
- Repository root: current working directory.
- Playwright results dir: \`${RESULTS_DIR}\` (traces \`trace.zip\`, \`test-failed-*.png\`, \`video.webm\`, \`error-context.md\`).
- HTML report dir: \`$(dirname "$RESULTS_DIR")/playwright-report\`.
- Container logs: \`${ARTIFACTS_DIR}/compose-logs.txt\` (secrets redacted).
- Write your final answer to: \`${OUTPUT_FILE}\`.

# Failure summary (from results.json)
CTX
node "$ROOT/e2e/scripts/summarize-results.mjs" "$RESULTS_DIR/results.json" "$ARTIFACTS_DIR"
